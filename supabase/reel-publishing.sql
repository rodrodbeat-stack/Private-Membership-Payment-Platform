-- Creates the public media bucket, community posts table, and minimum RLS policies.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('reel-media', 'reel-media', true, 104857600,
  array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public=true, file_size_limit=104857600,
  allowed_mime_types=excluded.allowed_mime_types;

create table if not exists public.reel_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  caption text default '',
  media_url text not null,
  media_type text not null check (media_type in ('image','video')),
  author_name text,
  created_at timestamptz not null default now()
);
alter table public.reel_posts enable row level security;
drop policy if exists "Public can read reels" on public.reel_posts;
create policy "Public can read reels" on public.reel_posts for select using (true);
drop policy if exists "Members can publish reels" on public.reel_posts;
create policy "Members can publish reels" on public.reel_posts for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Members can delete own reels" on public.reel_posts;
create policy "Members can delete own reels" on public.reel_posts for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Public can view reel media" on storage.objects;
create policy "Public can view reel media" on storage.objects for select using (bucket_id = 'reel-media');
drop policy if exists "Members can upload own reel media" on storage.objects;
create policy "Members can upload own reel media" on storage.objects for insert to authenticated
with check (bucket_id = 'reel-media' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Members can delete own reel media" on storage.objects;
create policy "Members can delete own reel media" on storage.objects for delete to authenticated
using (bucket_id = 'reel-media' and (storage.foldername(name))[1] = auth.uid()::text);
